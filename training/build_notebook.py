def build():
    cells = []
    for kind, text in CELLS:
        lines = text.split("\n")
        source = [line + "\n" for line in lines[:-1]] + [lines[-1]]
        cell = {"cell_type": kind, "metadata": {}, "source": source}
        if kind == "code":
            cell["execution_count"] = None
            cell["outputs"] = []
        cells.append(cell)
    nb = {
        "cells": cells,
        "metadata": {
            "accelerator": "GPU",
            "colab": {"provenance": [], "gpuType": "L4"},
            "kernelspec": {"display_name": "Python 3", "name": "python3"},
            "language_info": {"name": "python"},
        },
        "nbformat": 4,
        "nbformat_minor": 5,
    }
    OUT.write_text(json.dumps(nb, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    return len(cells)


SCRIPT = OUT.with_name("p9_train.py")


def build_script():
    """Write the same code cells as a plain script, for running detached on the
    VM (a dropped Colab CLI connection cannot stop it; see README.md). `!` shell
    lines become subprocess calls, `display()` prints, and every cell logs
    `[p9] cell N start/done` so progress can be read from the log."""
    out = ['"""P9 training as a plain script, generated by build_notebook.py from the same cells as p9_train.ipynb.',
           'Do not edit; edit build_notebook.py. Run detached on the Colab VM:',
           '  nohup python -u /content/p9/p9_train.py > /content/p9/train.log 2>&1 &',
           '"""',
           "import subprocess as _sp",
           "",
           "",
           "def display(x):  # notebook display() -> plain print",
           "    print(x)",
           ""]
    n = 0
    for kind, text in CELLS:
        if kind != "code":
            continue
        n += 1
        lines = []
        for line in text.strip("\n").split("\n"):
            stripped = line.lstrip()
            if stripped.startswith("!"):
                indent = line[: len(line) - len(stripped)]
                lines.append(f"{indent}_sp.run({stripped[1:]!r}, shell=True, check=False)")
            else:
                lines.append(line)
        body = "\n".join(lines).rstrip()
        # a bare last expression is notebook output; print the ones worth seeing
        body = re.sub(r"\n(LIB_VERSIONS|summary)\s*$", r"\nprint(\1)", body)
        out += [f"# ---------------- cell {n}", f'print("[p9] cell {n} start", flush=True)', body,
                f'print("[p9] cell {n} done", flush=True)', ""]
    SCRIPT.write_text("\n".join(out) + "\n", encoding="utf-8")
    return n


